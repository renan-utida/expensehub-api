using System;
using System.Collections.Generic;
using System.Linq;
using ExpenseHub.Api.Domain.Entities;
using ExpenseHub.Api.Domain.Enums;

namespace ExpenseHub.Api.Reports;

/// <summary>
/// The envelope of a report: what <c>POST /api/reports</c> answers with, and what the detail and the list return.
/// The instants are UTC <see cref="DateTime"/> values, so they are written ending in <c>Z</c>.
/// Each state fills only its own fields: <c>Pending</c> has the creation instant; <c>Processing</c> adds the start;
/// <c>Completed</c> adds the completion and the result; <c>Failed</c> adds the completion and the error.
/// </summary>
/// <param name="Id">The identifier generated by the server.</param>
/// <param name="Scope">The scope, as text: <c>Mine</c> or <c>Global</c>.</param>
/// <param name="FromDate">The first day of the period, inclusive.</param>
/// <param name="ToDate">The last day of the period, inclusive.</param>
/// <param name="Status">The state, as text.</param>
/// <param name="CreatedAt">The UTC instant the request was registered.</param>
/// <param name="StartedAt">The UTC instant the processing started, or <c>null</c>.</param>
/// <param name="CompletedAt">The UTC instant the request completed or failed, or <c>null</c>.</param>
/// <param name="Result">The saved result, only when the request is completed.</param>
/// <param name="Error">The error, only when the request failed.</param>
public sealed record ReportResponse(
    Guid Id,
    string Scope,
    DateOnly FromDate,
    DateOnly ToDate,
    string Status,
    DateTime CreatedAt,
    DateTime? StartedAt,
    DateTime? CompletedAt,
    ReportResultResponse? Result,
    ReportErrorResponse? Error)
{
    private const string UnknownErrorCode = "Unknown";

    /// <summary>
    /// Builds the envelope of a request. The result is read from what was saved; nothing is recalculated.
    /// </summary>
    /// <param name="report">The request.</param>
    /// <returns>The public representation.</returns>
    /// <exception cref="InvalidOperationException">The saved result of a completed request cannot be read.</exception>
    public static ReportResponse From(ReportRequest report)
    {
        ArgumentNullException.ThrowIfNull(report);

        ReportResultResponse? result = report.Status == ReportStatus.Completed && report.ResultJson is not null
            ? ReportResultResponse.From(ReportResultSerializer.Deserialize(report.ResultJson))
            : null;

        ReportErrorResponse? error = report.Status == ReportStatus.Failed
            ? new ReportErrorResponse(report.ErrorCode ?? UnknownErrorCode, report.ErrorMessage ?? string.Empty)
            : null;

        return new ReportResponse(
            report.Id,
            report.Scope.ToString(),
            report.FromDate,
            report.ToDate,
            report.Status.ToString(),
            report.CreatedAtUtc.UtcDateTime,
            report.StartedAtUtc?.UtcDateTime,
            report.CompletedAtUtc?.UtcDateTime,
            result,
            error);
    }
}

/// <summary>
/// The saved result of a completed report.
/// </summary>
/// <param name="GeneratedAt">The UTC instant the result was calculated.</param>
/// <param name="TotalCount">The number of expenses of all the states.</param>
/// <param name="TotalAmount">The sum of the amounts of all the states.</param>
/// <param name="ByStatus">The five states, each with its count and amount, zero when empty.</param>
public sealed record ReportResultResponse(
    DateTime GeneratedAt,
    int TotalCount,
    decimal TotalAmount,
    IReadOnlyList<ReportStatusTotalResponse> ByStatus)
{
    /// <summary>
    /// Builds the public representation of a saved result.
    /// </summary>
    /// <param name="summary">The saved result.</param>
    /// <returns>The public representation.</returns>
    public static ReportResultResponse From(ReportSummary summary)
    {
        ArgumentNullException.ThrowIfNull(summary);

        return new ReportResultResponse(
            summary.GeneratedAtUtc.UtcDateTime,
            summary.TotalCount,
            summary.TotalAmount,
            summary.ByStatus.Select(total => new ReportStatusTotalResponse(total.Status.ToString(), total.Count, total.Amount)).ToList());
    }
}

/// <summary>
/// The count and the amount of the expenses in one state.
/// </summary>
/// <param name="Status">The state, as text.</param>
/// <param name="Count">The number of expenses in the state.</param>
/// <param name="Amount">The sum of their amounts.</param>
public sealed record ReportStatusTotalResponse(string Status, int Count, decimal Amount);

/// <summary>
/// The error of a failed report. The code is stable; the message is sanitized and never carries internal details.
/// </summary>
/// <param name="Code">The stable code of the error.</param>
/// <param name="Message">The sanitized message.</param>
public sealed record ReportErrorResponse(string Code, string Message);
